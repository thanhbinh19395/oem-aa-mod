#!/usr/bin/env python3
"""Generate quantized inner-10x8 speed-limit sign templates for ESP32-S3.

Reads VietMap Live HUD speed-limit sign JPEGs (`lib/assets/hud/{30..120}.png`)
from an extracted IPA/APK, box-downsamples each to 16x16 grayscale using the
exact integer BT.601 luma formula used by the ESP32 TJpgDec callback, extracts
the inner 10x8 digit region (rows 4..11, cols 3..12 -> 80 values, skipping the
shared outer red ring for high inter-digit margin and zero false positives on
non-speed warning signs), and writes
`firmware/vmhud-esp32-s3/lib/vmhud/speed_sign_templates.h`.

Usage:
    python3 firmware/vmhud-esp32-s3/scripts/gen_speed_sign_templates.py \
        --hud-dir tmp/vietmap_ipa_extract/Payload/Runner.app/Frameworks/App.framework/flutter_assets/lib/assets/hud \
        --out firmware/vmhud-esp32-s3/lib/vmhud/speed_sign_templates.h
"""
from __future__ import annotations

import argparse
import glob
import math
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_arrow_templates as arrow_gen  # reuse exact MAC_HELPER_C / box16 decoder

# Inner 10x8 region inside the 16x16 luma grid (rows 4..11, cols 3..12 = 80 cells).
# Verified across all 10 VietMap speed signs (30..120) and all other HUD warning signs:
#   - Min inter-digit NCC margin: 0.0597 (80 vs 90)
#   - Max false-positive NCC across all non-speed warning signs: 0.4337
ROW_START = 4
ROW_END = 12
COL_START = 3
COL_END = 13
FEAT_LEN = (ROW_END - ROW_START) * (COL_END - COL_START)


def inner_to_vec(luma16: list[int]) -> tuple[list[int], float]:
    px = [luma16[r * 16 + c] for r in range(ROW_START, ROW_END) for c in range(COL_START, COL_END)]
    mean = sum(px) / float(FEAT_LEN)
    centered = [x - mean for x in px]
    mabs = max(abs(x) for x in centered)
    if mabs < 1.0:
        raise ValueError("Blank/uniform speed sign image")
    vec = [max(-127, min(127, int(round(x * 127.0 / mabs)))) for x in centered]
    norm_sq = sum(v * v for v in vec)
    return vec, 1.0 / math.sqrt(norm_sq)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--hud-dir", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    speed_files: list[tuple[int, str]] = []
    for p in sorted(glob.glob(os.path.join(args.hud_dir, "*.png"))):
        stem = os.path.basename(p)[:-4]
        if stem.isdigit():
            val = int(stem)
            if 10 <= val <= 200:
                speed_files.append((val, p))
    speed_files.sort()
    if not speed_files:
        raise SystemExit(f"No speed limit sign images found in {args.hud_dir}")

    with tempfile.TemporaryDirectory() as td:
        c_path = os.path.join(td, "dec.c")
        bin_path = os.path.join(td, "dec")
        with open(c_path, "w", encoding="utf-8") as f:
            f.write(arrow_gen.MAC_HELPER_C)
        subprocess.check_call(
            [
                "clang",
                "-O2",
                c_path,
                "-framework",
                "ImageIO",
                "-framework",
                "CoreGraphics",
                "-framework",
                "CoreFoundation",
                "-o",
                bin_path,
            ]
        )

        entries: list[tuple[int, list[int], float]] = []
        for lim, p in speed_files:
            out = subprocess.check_output([bin_path, p], text=True).strip()
            luma = [int(x) for x in out.split(",")]
            if len(luma) != 256:
                raise RuntimeError(f"Unexpected luma len {len(luma)} for {p}")
            vec, inv_norm = inner_to_vec(luma)
            entries.append((lim, vec, inv_norm))

    lines: list[str] = [
        "// Auto-generated by scripts/gen_speed_sign_templates.py — DO NOT EDIT.",
        "// Quantized inner-10x8 (rows 4..11, cols 3..12 of 16x16 luma) speed-limit",
        "// sign descriptors from VietMap Live HUD assets (30..120 km/h).",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace vmhud {",
        "",
        f"static constexpr size_t kSpeedSignRowStart = {ROW_START};",
        f"static constexpr size_t kSpeedSignRowEnd   = {ROW_END};",
        f"static constexpr size_t kSpeedSignColStart = {COL_START};",
        f"static constexpr size_t kSpeedSignColEnd   = {COL_END};",
        f"static constexpr size_t kSpeedSignFeatLen  = {FEAT_LEN};",
        "",
        "struct SpeedSignTemplate {",
        "  uint8_t limit;",
        "  float   invNorm;",
        "  int8_t  vec[kSpeedSignFeatLen];",
        "};",
        "",
        f"static constexpr size_t kSpeedSignTemplateCount = {len(entries)};",
        "",
        "static const SpeedSignTemplate kSpeedSignTemplates[kSpeedSignTemplateCount] = {",
    ]
    for lim, vec, inv_norm in entries:
        vec_str = ",".join(str(v) for v in vec)
        lines.append(f"  {{{lim}u, {inv_norm:.9g}f, {{{vec_str}}}}},")
    lines.extend(
        [
            "};",
            "",
            "}  // namespace vmhud",
            "",
        ]
    )

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {len(entries)} speed-sign templates -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
